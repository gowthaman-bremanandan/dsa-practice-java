package practices.multiThread;

public class NumberRules {

    public static Integer doubleValue(Integer num) {

        return num * 2;
    }

    public static Integer square(Integer num) {

        return num * num;
    }

    public static Integer cube(Integer num) {

        return num * num * num;
    }

    public static Integer increment(Integer num) {

        return num + 1;
    }

    public static Integer print(Integer num) {

        return num;
    }
}